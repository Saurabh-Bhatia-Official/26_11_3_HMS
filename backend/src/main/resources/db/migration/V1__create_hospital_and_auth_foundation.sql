CREATE SEQUENCE hospital_public_id_sequence START WITH 1 INCREMENT BY 1;

CREATE TABLE hospitals (
    hospital_uuid UUID NOT NULL,
    hospital_id BIGINT,
    name VARCHAR(255) NOT NULL,
    code VARCHAR(255) NOT NULL,
    type VARCHAR(255) NOT NULL,
    address VARCHAR(255),
    phone VARCHAR(255),
    email VARCHAR(255),
    tax_id VARCHAR(255),
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_hospitals PRIMARY KEY (hospital_uuid),
    CONSTRAINT uk_hospital_public_id UNIQUE (hospital_id),
    CONSTRAINT ck_hospital_public_id_12_digits CHECK
        (hospital_id IS NULL OR hospital_id BETWEEN 100000000000 AND 999999999999)
);
CREATE INDEX ix_hospital_status_name ON hospitals(status, name);

CREATE TABLE hospital_id_allocations (
    allocation_number BIGINT NOT NULL PRIMARY KEY
);

CREATE TABLE auth_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name VARCHAR(160) NOT NULL,
    role VARCHAR(32) NOT NULL,
    hospital_id BIGINT,
    active BOOLEAN NOT NULL,
    failed_login_attempts INTEGER NOT NULL,
    locked_until TIMESTAMP WITH TIME ZONE,
    token_version BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT uk_auth_account_username UNIQUE (username)
);
CREATE INDEX ix_auth_account_hospital ON auth_accounts(hospital_id);

CREATE TABLE hospital_registrations (
    registration_uuid UUID NOT NULL PRIMARY KEY,
    hospital_uuid UUID NOT NULL,
    admin_username VARCHAR(64) NOT NULL,
    admin_username_reservation VARCHAR(64),
    admin_full_name VARCHAR(160) NOT NULL,
    admin_password_hash VARCHAR(100),
    status VARCHAR(16) NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    reviewed_by_account_id BIGINT,
    CONSTRAINT uk_hospital_registration_hospital UNIQUE (hospital_uuid),
    CONSTRAINT uk_hospital_registration_pending_admin_username UNIQUE (admin_username_reservation),
    CONSTRAINT fk_hospital_registration_hospital FOREIGN KEY (hospital_uuid) REFERENCES hospitals(hospital_uuid)
);
CREATE INDEX ix_hospital_registration_status_date ON hospital_registrations(status, submitted_at);
