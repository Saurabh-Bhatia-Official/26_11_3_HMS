-- One current vitals record per OPD visit. Numeric visit IDs are retained;
-- hospital UUID is carried on every row to enforce tenant isolation.
CREATE UNIQUE INDEX IF NOT EXISTS ux_opd_visit_id_hospital_uuid
    ON public.opd_visits (id, hospital_uuid);

CREATE TABLE public.opd_vitals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL DEFAULT gen_random_uuid(),
    visit_id BIGINT NOT NULL,
    hospital_uuid UUID NOT NULL,
    bp_systolic INTEGER,
    bp_diastolic INTEGER,
    pulse INTEGER,
    temperature_c NUMERIC(4,1),
    spo2 INTEGER,
    weight_kg NUMERIC(6,2),
    height_cm NUMERIC(6,2),
    bmi NUMERIC(5,2),
    recorded_by BIGINT NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes VARCHAR(2000),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_opd_vitals_uuid UNIQUE (uuid),
    CONSTRAINT uk_opd_vitals_visit_hospital UNIQUE (visit_id, hospital_uuid),
    CONSTRAINT fk_opd_vitals_visit_hospital
        FOREIGN KEY (visit_id, hospital_uuid)
        REFERENCES public.opd_visits (id, hospital_uuid),
    CONSTRAINT fk_opd_vitals_hospital
        FOREIGN KEY (hospital_uuid)
        REFERENCES public.hospitals (hospital_uuid),
    CONSTRAINT fk_opd_vitals_recorded_by
        FOREIGN KEY (recorded_by)
        REFERENCES public.auth_accounts (id),
    CONSTRAINT ck_opd_vitals_bp_pair
        CHECK ((bp_systolic IS NULL AND bp_diastolic IS NULL)
            OR (bp_systolic IS NOT NULL AND bp_diastolic IS NOT NULL
                AND bp_systolic > bp_diastolic)),
    CONSTRAINT ck_opd_vitals_bp_systolic
        CHECK (bp_systolic IS NULL OR bp_systolic BETWEEN 50 AND 300),
    CONSTRAINT ck_opd_vitals_bp_diastolic
        CHECK (bp_diastolic IS NULL OR bp_diastolic BETWEEN 30 AND 200),
    CONSTRAINT ck_opd_vitals_pulse
        CHECK (pulse IS NULL OR pulse BETWEEN 20 AND 250),
    CONSTRAINT ck_opd_vitals_temperature
        CHECK (temperature_c IS NULL OR temperature_c BETWEEN 25.0 AND 45.0),
    CONSTRAINT ck_opd_vitals_spo2
        CHECK (spo2 IS NULL OR spo2 BETWEEN 0 AND 100),
    CONSTRAINT ck_opd_vitals_weight
        CHECK (weight_kg IS NULL OR weight_kg BETWEEN 0.5 AND 500.0),
    CONSTRAINT ck_opd_vitals_height
        CHECK (height_cm IS NULL OR height_cm BETWEEN 30.0 AND 250.0)
);

CREATE INDEX ix_opd_vitals_hospital_recorded
    ON public.opd_vitals (hospital_uuid, recorded_at DESC);
