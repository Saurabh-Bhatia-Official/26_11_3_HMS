CREATE TABLE auth_refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    hospital_id BIGINT,
    family_id VARCHAR(36),
    revoked BOOLEAN NOT NULL,
    CONSTRAINT uk_auth_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_auth_refresh_account FOREIGN KEY (account_id) REFERENCES auth_accounts(id)
);
CREATE INDEX ix_auth_refresh_expires_at ON auth_refresh_tokens(expires_at);
CREATE INDEX ix_auth_refresh_family_id ON auth_refresh_tokens(family_id);

CREATE TABLE security_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(32) NOT NULL,
    account_id BIGINT,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_security_audit_occurred_at ON security_audit_events(occurred_at);
CREATE INDEX ix_security_audit_account_id ON security_audit_events(account_id);
